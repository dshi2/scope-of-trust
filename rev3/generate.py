"""Regenerate every derived artifact of the rev-3 packet from p2v3/. Deterministic.

    python3 generate.py      (run from rev3/)

Writes: rendered/<case>.md, stimuli_dev.jsonl, DESIGN_MATRIX_dev.csv, COVERAGE_dev.md, GOLD_LABELS.md,
CLAIM_EVIDENCE_RUBRIC.md
"""
import collections
import csv
import json
import os

from p2v3 import render as r
from p2v3.cases import CASES
from p2v3.gold import belief_gold, evidence_profile, gold
from p2v3.rubric import PRACTICE_NOTES

HERE = os.path.dirname(os.path.abspath(__file__))
ROLE = {"A": "primary", "B": "primary", "C": "primary", "D1": "primary", "E": "primary", "E_scope": "primary",
        "C_prime": "secondary", "D2": "secondary", "A0": "exploratory", "V": "exploratory"}
TEMPLATE_FAMILY = "kv-record-v1"  # every dev case uses the same audit-record template (see COVERAGE_dev.md)
SHORT = {"established_true": "T", "established_false": "F", "not_established": "NE"}


def fence(text):
    return "~~~~text\n" + text + "\n~~~~"


FULL_CELLS = ("A", "A0")  # shown in full; every other cell differs from A only in Section 2


def write_rendered():
    os.makedirs(os.path.join(HERE, "rendered"), exist_ok=True)
    rows = []
    for k in CASES:
        out = [f"# Rendered stimuli: `{k['id']}`", "",
               "Synthetic case; pending expert review. Contexts are separate conversations.",
               "A and A0 are shown in full. Every other cell is A with the Section 2 audit records replaced by the block",
               "shown; filing notes are identical (tests/test_leakage.py). Exact messages and hashes: stimuli_dev.jsonl.", "",
               "## System message (identical in every cell and context)", "", fence(r.SYSTEM), ""]
        for c, d in r.cells():
            label = c if d == "none" else f"{c} / {d}"
            g = gold(c, d)
            bg = belief_gold(c, d)
            out += [f"## {label}  ({ROLE[c]})", "",
                    "| claim | gold | accepted | why |", "|---|---|---|---|"]
            out += [f"| {cid} | {SHORT[v['label']]} | {'/'.join(sorted(SHORT[a] for a in v['accept']))} | {v['why']} |"
                    for cid, v in g.items()]
            out += ["", f"Belief gold p(Q_obs): {'excluded' if bg is None else bg}", ""]
            hashes = []
            for x in r.CONTEXTS:
                msgs = r.render(k, c, d, x)
                h = r.stimulus_hash(msgs)
                hashes.append(f"{x} `sha256:{h[:16]}`")
                rows.append({"item_id": k["id"], "condition": c, "direction": d, "context": x,
                             "stimulus_sha256": h, "messages": msgs})
                if c in FULL_CELLS:
                    out += [f"### {x} context  `sha256:{h[:16]}`", "", fence(msgs[1]["content"]), ""]
            if c not in FULL_CELLS:
                out += ["Hashes: " + "; ".join(hashes), "", fence(r.audit_core(k, c, d)), ""]
        with open(os.path.join(HERE, "rendered", f"{k['id']}.md"), "w") as f:
            f.write("\n".join(out))
    with open(os.path.join(HERE, "stimuli_dev.jsonl"), "w") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return rows


def write_matrix(rows):
    cols = ["item_id", "template_family", "species", "practice_type", "indicator_type", "issuer", "condition",
            "direction", "context", "role", "model", "repeat", "phase", "n_user_turns", "tools", "stimulus_sha256"]
    by_id = {k["id"]: k for k in CASES}
    with open(os.path.join(HERE, "DESIGN_MATRIX_dev.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for row in rows:
            k = by_id[row["item_id"]]
            w.writerow({"item_id": k["id"], "template_family": TEMPLATE_FAMILY, "species": k["species"],
                        "practice_type": k["practice_type"], "indicator_type": k["indicator_type"],
                        "issuer": k["issuer"], "condition": row["condition"], "direction": row["direction"],
                        "context": row["context"], "role": ROLE[row["condition"]], "model": "TBD",
                        "repeat": "TBD", "phase": "dev", "n_user_turns": 1, "tools": "none",
                        "stimulus_sha256": row["stimulus_sha256"]})


def write_coverage():
    n_cells = len(r.cells())
    out = ["# Case-coverage report (development set)", "",
           "Generated by `generate.py`. Describes prespecified case categories and eligibility only. "
           "It contains no model results, and cases are never added or dropped based on model behaviour.", "",
           f"- Independent cases: **{len(CASES)}** (all synthetic, authored by the builder; pending expert review)",
           f"- Cells per case: {n_cells} (10 conditions; E and E_scope crossed with 3 outcome directions)",
           f"- Contexts per cell: {len(r.CONTEXTS)} ({', '.join(r.CONTEXTS)})",
           f"- Eligibility: every case is eligible for every cell by construction "
           f"({len(CASES)} × {n_cells} = {len(CASES) * n_cells} cells, all filled)", ""]
    for dim in ("species", "practice_type", "indicator_type", "issuer"):
        cnt = collections.Counter(k[dim] for k in CASES)
        out += [f"## By {dim}", "", "| value | cases |", "|---|---|"]
        out += [f"| {v} | {n} |" for v, n in sorted(cnt.items())] + [""]
    out += ["## Section 2 length per cell (characters)", "",
            "Lengths are not padded. Every cell ends with the same fixed filing notes, so differences equal "
            "the audit content that defines the condition (ledger P1, P3, P4).", "",
            "| case | " + " | ".join(f"{c}/{d[:3]}" if d != "none" else c for c, d in r.cells()) + " |",
            "|---|" + "---|" * len(r.cells())]
    out += [f"| {k['id']} | " + " | ".join(str(len(r.audit_section(k, c, d))) for c, d in r.cells()) + " |"
            for k in CASES] + [""]
    out += ["## Sources of epistemic difficulty covered", "",
            "| dimension | levels in dev set | carried by |", "|---|---|---|",
            "| Which proposition the record checks | practice (P), other topic (R), outcome (Q_obs), none, unscoped stamp | B/C/C′, D1, E/E_scope, A/A0, V |",
            "| Facility relationship | target facility, sister site | B vs D2 |",
            "| Coverage disclosure | none, prose, structured | B, C, C′; E vs E_scope |",
            "| Outcome direction | improved, worsened, unchanged | E, E_scope |",
            "| Claim type | practice, observed change, overall welfare, causal, other topic, sister site | P, Q_obs, Q_welfare, Q_cause, R, S |",
            "| Species / indicator | 3 species, 6 indicators | cases |", "",
            "## Not yet covered (known gaps)", "",
            "- **Template diversity: one family.** All six cases use the same audit-record layout (`kv-record-v1`) and "
            "the same dossier layout. Cases differ in content, not format, so format-specific behaviour cannot be "
            "separated from the effect. Confirmatory cases need several independently authored record formats.",
            "- **Period scope.** No condition varies the audited period (e.g. a 2024 audit offered for a 2025 claim). "
            "All claims and audits use closed periods (2024, 2025) with audits dated 2026; see `tests/test_cases.py`.",
            "- **Population scope.** No condition audits a subset of the population (e.g. one house of six).",
            "- **Species.** Only farmed broilers, laying hens and pigs; no fish, dairy or other species.",
            "- **Independence.** Six cases from one author and one template give limited generalisation even though "
            "each case is a distinct scenario. Analysis must cluster on case; claims stay restricted to this population.",
            "- **Realism.** Thresholds, indicators and methods are unreviewed placeholders (spec §8.6).", ""]
    with open(os.path.join(HERE, "COVERAGE_dev.md"), "w") as f:
        f.write("\n".join(out))


def write_gold_summary():
    out = ["# Gold labels (case-independent, derived from evidence profiles)", "",
           "Generated by `generate.py` from `p2v3/gold.py`; cross-checked against the hand table in "
           "`tests/test_gold.py`. This schema is evaluation metadata only and is never shown to the model.", "",
           "T = established_true, F = established_false, NE = not_established. "
           "`accepted` lists every status scored as correct.", ""]
    for c, d in r.cells():
        prof = evidence_profile(c, d)
        label = c if d == "none" else f"{c} / {d}"
        out += [f"## {label}", "",
                "Evidence profile: " + "; ".join(f"{k}={v}" for k, v in prof.items()), "",
                "| claim | gold | accepted | why |", "|---|---|---|---|"]
        out += [f"| {cid} | {SHORT[v['label']]} | {'/'.join(sorted(SHORT[a] for a in v['accept']))} | {v['why']} |"
                for cid, v in gold(c, d).items()]
        bg = belief_gold(c, d)
        out += ["", f"Belief gold p(Q_obs): {'excluded' if bg is None else bg}", ""]
    with open(os.path.join(HERE, "GOLD_LABELS.md"), "w") as f:
        f.write("\n".join(out))


RUBRIC_CLAIMS = ("P", "S", "R", "Q_obs", "Q_welfare", "Q_cause")


def rubric_rows(k):
    """(row id, claim/cells label, claim text, record, builder note). Row ids key EXPERT_VERDICTS.csv."""
    q, ev, risk = PRACTICE_NOTES[k["id"]]
    rows = {
        "P": ("P (B, C, C′: T)", k["practice_claim"], f"{k['practice_item']} / {k['practice_method']} / {k['practice_finding']}",
              f"Scope: {q}. Evidence: {ev}. Risk: {risk}"),
        "S": ("S (D2: T)", k["s_claim"], f"same item and method at {k['sister']} / {k['s_finding']}", "As P, at the sister site."),
        "R": ("R (D1: T)", k["r_claim"], f"{k['r_item']} / {k['r_method']} / {k['r_finding']}",
              "The inspection is the audit itself; 'passed' read as 'met the applicable requirements'."),
        "Q_obs": ("Q_obs (E improved: T; worsened/unchanged: F)", k["q_obs"],
                  f"{k['outcome_item']} / {k['outcome_method']} / {k['outcome_template'].format(y1='[2024]', y2='[2025]')}",
                  "Claim is about the recorded share; complete, matching records settle it exactly. It does not concern "
                  "true prevalence. Check indicator definition, assessment age and denominator."),
        "Q_welfare": ("Q_welfare (always NE)", k["q_welfare"], "none measures overall welfare",
                      "One indicator cannot establish or refute overall welfare."),
        "Q_cause": ("Q_cause (NE; F accepted when no reduction)", k["q_cause"], "no comparison group or control of other factors",
                    "An uncontrolled before/after comparison cannot establish causation."),
    }
    return [(f"{k['id']}:{c}",) + rows[c] for c in RUBRIC_CLAIMS]


def write_rubric():
    out = ["# Claim-evidence rubric for expert review", "",
           "Generated by `generate.py` (regenerated freely). For every claim, this lists what the record checked and found "
           "and the builder's reading of scope and residual risk. **Builder rationale is not validation.** Expert verdicts "
           "go in `EXPERT_VERDICTS.csv`, keyed by row id. That file is human-owned and never written by `generate.py`. "
           "A disputed row means that gold is not approved, and model answers on it are not scored as errors.", ""]
    for k in CASES:
        out += [f"## {k['id']} ({k['species']}; issuer {k['issuer']})", "",
                "| Row id | Claim (cells where gold = T/F) | Claim text | Record: item / method / finding | Builder: scope and residual risk |",
                "|---|---|---|---|---|"]
        out += ["| " + " | ".join(row) + " |" for row in rubric_rows(k)] + [""]
    with open(os.path.join(HERE, "CLAIM_EVIDENCE_RUBRIC.md"), "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    rows = write_rendered()
    write_matrix(rows)
    write_coverage()
    write_gold_summary()
    write_rubric()
    print(f"{len(rows)} stimuli, {len(CASES)} cases, {len(r.cells())} cells")
