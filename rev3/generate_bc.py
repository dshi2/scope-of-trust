"""Regenerate the derived artifacts of expansion BATCH bc (p2v3/cases_bc.py). Deterministic.

    python3 generate_bc.py      (run from rev3/)

Uses the same renderer (p2v3/render.py: system prompt, task text, condition matrix, hashing),
gold and rubric code as generate.py / generate_ext.py, so batch rows have exactly the schema of
stimuli_dev.jsonl. Writes only batch-bc files and never touches base or extension artifacts:
  rendered/<bc case>.md, stimuli_bc.jsonl, DESIGN_MATRIX_bc.csv, COVERAGE_bc.md, CLAIM_EVIDENCE_RUBRIC_bc.md
EXPERT_VERDICTS.csv is human-owned and never written here (it has no batch-bc rows yet).
"""
import collections
import csv
import json
import os
from unittest import mock

import generate as g
from p2v3 import render as r
from p2v3.cases import CASES
from p2v3.cases_bc import BATCH, CASES_BC, PRACTICE_NOTES_BC
from p2v3.cases_ext import CASES_EXT
from p2v3.gold import belief_gold, gold

HERE = g.HERE
STIMULI = f"stimuli_{BATCH}.jsonl"
DEV_SHA = "368e1d0eeb5a56ef0a093f71d2655419ec1372925057f5ad875890cf624c8e67"
EXT_SHA = "c9d92a016db4ba9b31039ab2371ba6b221d8bbcd3b300fd994fade4b39b063d0"


def write_rendered():
    os.makedirs(os.path.join(HERE, "rendered"), exist_ok=True)
    rows = []
    for k in CASES_BC:
        out = [f"# Rendered stimuli: `{k['id']}` (expansion batch {BATCH})", "",
               "Synthetic case; pending expert review. Contexts are separate conversations.",
               "A and A0 are shown in full. Every other cell is A with the Section 2 audit records replaced by the block",
               f"shown; filing notes are identical (tests/test_leakage.py). Exact messages and hashes: {STIMULI}.", "",
               "## System message (identical in every cell and context)", "", g.fence(r.SYSTEM), ""]
        for c, d in r.cells():
            label = c if d == "none" else f"{c} / {d}"
            gl = gold(c, d)
            bg = belief_gold(c, d)
            out += [f"## {label}  ({g.ROLE[c]})", "",
                    "| claim | gold | accepted | why |", "|---|---|---|---|"]
            out += [f"| {cid} | {g.SHORT[v['label']]} | {'/'.join(sorted(g.SHORT[a] for a in v['accept']))} | {v['why']} |"
                    for cid, v in gl.items()]
            out += ["", f"Belief gold p(Q_obs): {'excluded' if bg is None else bg}", ""]
            hashes = []
            for x in r.CONTEXTS:
                msgs = r.render(k, c, d, x)
                h = r.stimulus_hash(msgs)
                hashes.append(f"{x} `sha256:{h[:16]}`")
                rows.append({"item_id": k["id"], "condition": c, "direction": d, "context": x,
                             "stimulus_sha256": h, "messages": msgs})
                if c in g.FULL_CELLS:
                    out += [f"### {x} context  `sha256:{h[:16]}`", "", g.fence(msgs[1]["content"]), ""]
            if c not in g.FULL_CELLS:
                out += ["Hashes: " + "; ".join(hashes), "", g.fence(r.audit_core(k, c, d)), ""]
        with open(os.path.join(HERE, "rendered", f"{k['id']}.md"), "w") as f:
            f.write("\n".join(out))
    with open(os.path.join(HERE, STIMULI), "w") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return rows


def write_matrix(rows):
    cols = ["item_id", "template_family", "species", "practice_type", "indicator_type", "issuer", "condition",
            "direction", "context", "role", "model", "repeat", "phase", "n_user_turns", "tools", "stimulus_sha256"]
    by_id = {k["id"]: k for k in CASES_BC}
    with open(os.path.join(HERE, f"DESIGN_MATRIX_{BATCH}.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for row in rows:
            k = by_id[row["item_id"]]
            w.writerow({"item_id": k["id"], "template_family": g.TEMPLATE_FAMILY, "species": k["species"],
                        "practice_type": k["practice_type"], "indicator_type": k["indicator_type"],
                        "issuer": k["issuer"], "condition": row["condition"], "direction": row["direction"],
                        "context": row["context"], "role": g.ROLE[row["condition"]], "model": "TBD",
                        "repeat": "TBD", "phase": f"dev-{BATCH}", "n_user_turns": 1, "tools": "none",
                        "stimulus_sha256": row["stimulus_sha256"]})


def write_coverage():
    n_cells = len(r.cells())
    allc = CASES + CASES_EXT + CASES_BC
    out = [f"# Case-coverage report (expansion batch {BATCH})", "",
           f"Generated by `generate_{BATCH}.py`. Describes prespecified case categories and eligibility only. "
           "It contains no model results, and cases are never added or dropped based on model behaviour.", "",
           f"**Batch declaration.** Batch {BATCH} is one of three separately authored batches (ba, bb, bc) of the "
           "PI-approved expansion from 12 to 36 development cases. It was authored after the base and extension stimuli "
           f"were frozen (`stimuli_dev.jsonl`, sha256 `{DEV_SHA[:8]}…{DEV_SHA[-4:]}`; `stimuli_ext.jsonl`, sha256 "
           f"`{EXT_SHA[:8]}…{EXT_SHA[-4:]}`) and is run as a separately declared batch (`{STIMULI}`) with the same frozen "
           "model configuration (`configs/p2_dev_eval_v1.json`), renderer, system prompt, task text and condition "
           "matrix. Batch cases were not selected or edited based on any model output. The reporting rule for the "
           "expansion is the one declared with the batch run; this file does not restate or change it.", "",
           f"- Independent batch-{BATCH} cases: **{len(CASES_BC)}** (all synthetic, builder-written development cases; "
           "pending expert review)",
           f"- With the base and extension sets: **{len(allc)}** cases, "
           f"{len({(k['species'], k['practice_type'], k['indicator_type']) for k in allc})} distinct "
           "species × practice × indicator families (batches ba and bb are counted in their own reports)",
           f"- Cells per case: {n_cells} (10 conditions; E and E_scope crossed with 3 outcome directions)",
           f"- Contexts per cell: {len(r.CONTEXTS)} ({', '.join(r.CONTEXTS)})",
           f"- Eligibility: every case is eligible for every cell by construction "
           f"({len(CASES_BC)} × {n_cells} = {len(CASES_BC) * n_cells} cells, all filled)", ""]
    for dim in ("species", "practice_type", "indicator_type", "issuer"):
        cnt = collections.Counter(k[dim] for k in CASES_BC)
        out += [f"## By {dim}", "", "| value | cases |", "|---|---|"]
        out += [f"| {v} | {n} |" for v, n in sorted(cnt.items())] + [""]
    out += ["## Outcome audit method per case", "", "| case | outcome item | outcome method |", "|---|---|---|"]
    out += [f"| {k['id']} | {k['outcome_item']} | {k['outcome_method']} |" for k in CASES_BC] + [""]
    out += ["## Section 2 length per cell (characters)", "",
            "Lengths are not padded. Every cell ends with the same fixed filing notes, so differences equal "
            "the audit content that defines the condition (ledger P1, P3, P4).", "",
            "| case | " + " | ".join(f"{c}/{d[:3]}" if d != "none" else c for c, d in r.cells()) + " |",
            "|---|" + "---|" * len(r.cells())]
    out += [f"| {k['id']} | " + " | ".join(str(len(r.audit_section(k, c, d))) for c, d in r.cells()) + " |"
            for k in CASES_BC] + [""]
    out += [f"## What batch {BATCH} adds", "",
            "- **Populations beyond farms:** laboratory mice and zebrafish (breeding suppliers), stray dogs in contracted "
            "kennels, cats and rabbits held for rehoming, working sled dogs at a tour operator, zoo marmosets and tamarins, "
            "trekking donkeys. Each operator supplies animals or an animal-based service under contract, so "
            "the frozen \"procurement committee / supplier\" wording applies unchanged.",
            "- **Practice types:** nesting material, water quality, kennel enrichment, hiding places, workload limit, "
            "enclosure space, foraging enrichment, rider and pack-load limit.",
            "- **Outcome evidence sources:** coat scoring by a technician from outside the breeding team, daily health-check "
            "removals against a tank census, day-7 scoring by a contracted behaviourist, veterinary nurse weighing records, "
            "a contracted vet's clinical records, weekly checks by a duty animal care officer, quarterly alopecia scoring by "
            "a veterinary team, quarterly yard visits by a regional animal health officer.",
            "- **Indicators:** barbering, illness removals, kennel repetitive behaviour, weight loss after admission, "
            "lameness/strain treatments, bar-biting or repetitive digging, alopecia, saddle or girth sores.",
            "- **Issuers:** eight new fictional issuers (none shared with the base or extension sets).", "",
            "## Not covered (known gaps, unchanged by this batch)", "",
            "- **Template diversity: one family.** Batch cases use the same audit-record layout (`kv-record-v1`) and dossier "
            "layout as the base cases, by design (same renderer). Format-specific behaviour still cannot be separated from the effect.",
            "- **Period and population scope.** No condition varies the audited period or audits a subset of the population.",
            "- **Independence.** All cases come from one builder pipeline. Analysis must cluster on case.",
            "- **Realism.** Thresholds, indicators and methods are unreviewed placeholders (spec §8.6); "
            "`EXPERT_VERDICTS.csv` has no rows for batch-bc cases yet (human-owned file, not written by this script).", ""]
    with open(os.path.join(HERE, f"COVERAGE_{BATCH}.md"), "w") as f:
        f.write("\n".join(out))


def write_rubric():
    out = [f"# Claim-evidence rubric for expert review (expansion batch {BATCH})", "",
           f"Generated by `generate_{BATCH}.py`. Same structure as `CLAIM_EVIDENCE_RUBRIC.md`. **Builder rationale is not "
           "validation.** Expert verdicts go in `EXPERT_VERDICTS.csv`, keyed by row id; that file is human-owned and never "
           "written by a generator.", ""]
    # rubric_rows reads generate.PRACTICE_NOTES; add the batch notes only for the duration of this call.
    with mock.patch.dict(g.PRACTICE_NOTES, PRACTICE_NOTES_BC):
        for k in CASES_BC:
            out += [f"## {k['id']} ({k['species']}; issuer {k['issuer']})", "",
                    "| Row id | Claim (cells where gold = T/F) | Claim text | Record: item / method / finding | Builder: scope and residual risk |",
                    "|---|---|---|---|---|"]
            out += ["| " + " | ".join(row) + " |" for row in g.rubric_rows(k)] + [""]
    with open(os.path.join(HERE, f"CLAIM_EVIDENCE_RUBRIC_{BATCH}.md"), "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    rows = write_rendered()
    write_matrix(rows)
    write_coverage()
    write_rubric()
    print(f"{len(rows)} stimuli, {len(CASES_BC)} batch-{BATCH} cases, {len(r.cells())} cells")
