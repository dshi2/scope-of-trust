"""Regenerate the derived artifacts of the EXTENSION case set (p2v3/cases_ext.py). Deterministic.

    python3 generate_ext.py      (run from rev3/)

Uses the same renderer (p2v3/render.py: system prompt, task text, condition matrix, hashing),
gold and rubric code as generate.py, so extension rows have exactly the schema of stimuli_dev.jsonl.
Writes only extension files and never touches base artifacts:
  rendered/<ext case>.md, stimuli_ext.jsonl, DESIGN_MATRIX_ext.csv, COVERAGE_ext.md, CLAIM_EVIDENCE_RUBRIC_ext.md
EXPERT_VERDICTS.csv is human-owned and never written here.
"""
import collections
import csv
import json
import os

import generate as g
from p2v3 import render as r
from p2v3.cases import CASES
from p2v3.cases_ext import CASES_EXT
from p2v3.gold import belief_gold, gold

HERE = g.HERE


def write_rendered():
    os.makedirs(os.path.join(HERE, "rendered"), exist_ok=True)
    rows = []
    for k in CASES_EXT:
        out = [f"# Rendered stimuli: `{k['id']}` (extension set)", "",
               "Synthetic case; pending expert review. Contexts are separate conversations.",
               "A and A0 are shown in full. Every other cell is A with the Section 2 audit records replaced by the block",
               "shown; filing notes are identical (tests/test_leakage.py). Exact messages and hashes: stimuli_ext.jsonl.", "",
               "## System message (identical in every cell and context)", "", g.fence(r.SYSTEM), ""]
        for c, d in r.cells():
            label = c if d == "none" else f"{c} / {d}"
            gl = gold(c, d)
            bg = belief_gold(c, d)
            out += [f"## {label}  ({g.ROLE[c]})", "",
                    "| claim | gold | accepted | why |", "|---|---|---|---|"]
            out += [f"| {cid} | {g.SHORT[v['label']]} | {'/'.join(sorted(g.SHORT[a] for a in v['accept']))} | {v['why']} |"
                    for cid, v in gl.items()]
            out += ["", f"Belief gold p(Q_obs): {'excluded' if bg is None else bg}", ""]
            hashes = []
            for x in r.CONTEXTS:
                msgs = r.render(k, c, d, x)
                h = r.stimulus_hash(msgs)
                hashes.append(f"{x} `sha256:{h[:16]}`")
                rows.append({"item_id": k["id"], "condition": c, "direction": d, "context": x,
                             "stimulus_sha256": h, "messages": msgs})
                if c in g.FULL_CELLS:
                    out += [f"### {x} context  `sha256:{h[:16]}`", "", g.fence(msgs[1]["content"]), ""]
            if c not in g.FULL_CELLS:
                out += ["Hashes: " + "; ".join(hashes), "", g.fence(r.audit_core(k, c, d)), ""]
        with open(os.path.join(HERE, "rendered", f"{k['id']}.md"), "w") as f:
            f.write("\n".join(out))
    with open(os.path.join(HERE, "stimuli_ext.jsonl"), "w") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return rows


def write_matrix(rows):
    cols = ["item_id", "template_family", "species", "practice_type", "indicator_type", "issuer", "condition",
            "direction", "context", "role", "model", "repeat", "phase", "n_user_turns", "tools", "stimulus_sha256"]
    by_id = {k["id"]: k for k in CASES_EXT}
    with open(os.path.join(HERE, "DESIGN_MATRIX_ext.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for row in rows:
            k = by_id[row["item_id"]]
            w.writerow({"item_id": k["id"], "template_family": g.TEMPLATE_FAMILY, "species": k["species"],
                        "practice_type": k["practice_type"], "indicator_type": k["indicator_type"],
                        "issuer": k["issuer"], "condition": row["condition"], "direction": row["direction"],
                        "context": row["context"], "role": g.ROLE[row["condition"]], "model": "TBD",
                        "repeat": "TBD", "phase": "dev-ext", "n_user_turns": 1, "tools": "none",
                        "stimulus_sha256": row["stimulus_sha256"]})


def write_coverage():
    n_cells = len(r.cells())
    allc = CASES + CASES_EXT
    out = ["# Case-coverage report (extension set)", "",
           "Generated by `generate_ext.py`. Describes prespecified case categories and eligibility only. "
           "It contains no model results, and cases are never added or dropped based on model behaviour.", "",
           "**Pre-declared reporting rule.** The extension set was authored after the base run's stimuli were frozen "
           "(`stimuli_dev.jsonl`, sha256 `368e1d0e…8e67`) and is run separately with the same frozen model configuration "
           "(`configs/p2_dev_eval_v1.json`), renderer, system prompt, task text and condition matrix. If the extension run "
           "completes, it is reported alongside the base run (12 cases, 12 audit families); otherwise only the base run "
           "is reported. Extension cases were not selected or edited based on any model output.", "",
           f"- Independent extension cases: **{len(CASES_EXT)}** (all synthetic, authored by the builder; pending expert review)",
           f"- Combined with the base set: **{len(allc)}** cases, {len({(k['species'], k['practice_type'], k['indicator_type']) for k in allc})} distinct "
           "species × practice × indicator families",
           f"- Cells per case: {n_cells} (10 conditions; E and E_scope crossed with 3 outcome directions)",
           f"- Contexts per cell: {len(r.CONTEXTS)} ({', '.join(r.CONTEXTS)})",
           f"- Eligibility: every case is eligible for every cell by construction "
           f"({len(CASES_EXT)} × {n_cells} = {len(CASES_EXT) * n_cells} cells, all filled)", ""]
    for dim in ("species", "practice_type", "indicator_type", "issuer"):
        cnt = collections.Counter(k[dim] for k in CASES_EXT)
        out += [f"## By {dim}", "", "| value | cases |", "|---|---|"]
        out += [f"| {v} | {n} |" for v, n in sorted(cnt.items())] + [""]
    out += ["## Outcome audit method per case", "", "| case | outcome item | outcome method |", "|---|---|---|"]
    out += [f"| {k['id']} | {k['outcome_item']} | {k['outcome_method']} |" for k in CASES_EXT] + [""]
    out += ["## Section 2 length per cell (characters)", "",
            "Lengths are not padded. Every cell ends with the same fixed filing notes, so differences equal "
            "the audit content that defines the condition (ledger P1, P3, P4).", "",
            "| case | " + " | ".join(f"{c}/{d[:3]}" if d != "none" else c for c, d in r.cells()) + " |",
            "|---|" + "---|" * len(r.cells())]
    out += [f"| {k['id']} | " + " | ".join(str(len(r.audit_section(k, c, d))) for c, d in r.cells()) + " |"
            for k in CASES_EXT] + [""]
    out += ["## What the extension adds", "",
            "- **Species:** dairy cows, Atlantic salmon, turkeys, Pekin ducks, rabbits, dairy calves (base: broilers, laying hens, pigs).",
            "- **Practice types:** resource ratio, fish density, lighting programme, water provision, flooring, colostrum management.",
            "- **Outcome evidence sources:** contracted scorer sessions, processing-plant grading, cull sheets per bird placed, "
            "on-farm scoring at a fixed age, monthly whole-herd checks, medicine book reconciled with prescriptions.",
            "- **Issuers:** six new fictional issuers (no issuer shared with the base set).", "",
            "## Not covered (known gaps, unchanged by the extension)", "",
            "- **Template diversity: one family.** Extension cases use the same audit-record layout (`kv-record-v1`) and dossier "
            "layout as the base cases, by design (same renderer). Format-specific behaviour still cannot be separated from the effect.",
            "- **Period and population scope.** No condition varies the audited period or audits a subset of the population.",
            "- **Independence.** All twelve cases come from one author. Analysis must cluster on case.",
            "- **Realism.** Thresholds, indicators and methods are unreviewed placeholders (spec §8.6); "
            "`EXPERT_VERDICTS.csv` rows for the extension cases are blank.", ""]
    with open(os.path.join(HERE, "COVERAGE_ext.md"), "w") as f:
        f.write("\n".join(out))


def write_rubric():
    out = ["# Claim-evidence rubric for expert review (extension set)", "",
           "Generated by `generate_ext.py`. Same structure as `CLAIM_EVIDENCE_RUBRIC.md`. **Builder rationale is not "
           "validation.** Expert verdicts go in `EXPERT_VERDICTS.csv`, keyed by row id; that file is human-owned and never "
           "written by a generator.", ""]
    for k in CASES_EXT:
        out += [f"## {k['id']} ({k['species']}; issuer {k['issuer']})", "",
                "| Row id | Claim (cells where gold = T/F) | Claim text | Record: item / method / finding | Builder: scope and residual risk |",
                "|---|---|---|---|---|"]
        out += ["| " + " | ".join(row) + " |" for row in g.rubric_rows(k)] + [""]
    with open(os.path.join(HERE, "CLAIM_EVIDENCE_RUBRIC_ext.md"), "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    rows = write_rendered()
    write_matrix(rows)
    write_coverage()
    write_rubric()
    print(f"{len(rows)} stimuli, {len(CASES_EXT)} extension cases, {len(r.cells())} cells")
