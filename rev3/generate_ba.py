"""Regenerate the derived artifacts of expansion batch `ba` (p2v3/cases_ba.py). Deterministic.

    python3 generate_ba.py      (run from rev3/)

Uses the same renderer (p2v3/render.py: system prompt, task text, condition matrix, hashing),
gold and rubric code as generate.py / generate_ext.py, so batch rows have exactly the schema of
stimuli_dev.jsonl. Writes only batch files and never touches base or extension artifacts:
  rendered/<ba case>.md, stimuli_ba.jsonl, DESIGN_MATRIX_ba.csv, COVERAGE_ba.md, CLAIM_EVIDENCE_RUBRIC_ba.md
EXPERT_VERDICTS.csv is human-owned and never written here.
"""
import collections
import csv
import json
import os

import generate as g
from p2v3 import render as r
from p2v3.cases import CASES
from p2v3.cases_ba import CASES_BA, PRACTICE_NOTES_BA
from p2v3.cases_ext import CASES_EXT
from p2v3.gold import belief_gold, gold

HERE = g.HERE
TAG = "ba"
# generate.rubric_rows reads p2v3.rubric.PRACTICE_NOTES; add this batch's notes in memory only
# (p2v3/rubric.py is not edited).
g.PRACTICE_NOTES.update(PRACTICE_NOTES_BA)


def write_rendered():
    os.makedirs(os.path.join(HERE, "rendered"), exist_ok=True)
    rows = []
    for k in CASES_BA:
        out = [f"# Rendered stimuli: `{k['id']}` (expansion batch {TAG})", "",
               "Synthetic case; pending expert review. Contexts are separate conversations.",
               "A and A0 are shown in full. Every other cell is A with the Section 2 audit records replaced by the block",
               f"shown; filing notes are identical (tests/test_leakage.py). Exact messages and hashes: stimuli_{TAG}.jsonl.", "",
               "## System message (identical in every cell and context)", "", g.fence(r.SYSTEM), ""]
        for c, d in r.cells():
            label = c if d == "none" else f"{c} / {d}"
            gl = gold(c, d)
            bg = belief_gold(c, d)
            out += [f"## {label}  ({g.ROLE[c]})", "",
                    "| claim | gold | accepted | why |", "|---|---|---|---|"]
            out += [f"| {cid} | {g.SHORT[v['label']]} | {'/'.join(sorted(g.SHORT[a] for a in v['accept']))} | {v['why']} |"
                    for cid, v in gl.items()]
            out += ["", f"Belief gold p(Q_obs): {'excluded' if bg is None else bg}", ""]
            hashes = []
            for x in r.CONTEXTS:
                msgs = r.render(k, c, d, x)
                h = r.stimulus_hash(msgs)
                hashes.append(f"{x} `sha256:{h[:16]}`")
                rows.append({"item_id": k["id"], "condition": c, "direction": d, "context": x,
                             "stimulus_sha256": h, "messages": msgs})
                if c in g.FULL_CELLS:
                    out += [f"### {x} context  `sha256:{h[:16]}`", "", g.fence(msgs[1]["content"]), ""]
            if c not in g.FULL_CELLS:
                out += ["Hashes: " + "; ".join(hashes), "", g.fence(r.audit_core(k, c, d)), ""]
        with open(os.path.join(HERE, "rendered", f"{k['id']}.md"), "w") as f:
            f.write("\n".join(out))
    with open(os.path.join(HERE, f"stimuli_{TAG}.jsonl"), "w") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return rows


def write_matrix(rows):
    cols = ["item_id", "template_family", "species", "practice_type", "indicator_type", "issuer", "condition",
            "direction", "context", "role", "model", "repeat", "phase", "n_user_turns", "tools", "stimulus_sha256"]
    by_id = {k["id"]: k for k in CASES_BA}
    with open(os.path.join(HERE, f"DESIGN_MATRIX_{TAG}.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for row in rows:
            k = by_id[row["item_id"]]
            w.writerow({"item_id": k["id"], "template_family": g.TEMPLATE_FAMILY, "species": k["species"],
                        "practice_type": k["practice_type"], "indicator_type": k["indicator_type"],
                        "issuer": k["issuer"], "condition": row["condition"], "direction": row["direction"],
                        "context": row["context"], "role": g.ROLE[row["condition"]], "model": "TBD",
                        "repeat": "TBD", "phase": f"dev-{TAG}", "n_user_turns": 1, "tools": "none",
                        "stimulus_sha256": row["stimulus_sha256"]})


def write_coverage():
    n_cells = len(r.cells())
    prior = CASES + CASES_EXT
    allc = prior + CASES_BA
    fam = lambda ks: {(k["species"], k["practice_type"], k["indicator_type"]) for k in ks}
    out = [f"# Case-coverage report (expansion batch {TAG})", "",
           f"Generated by `generate_{TAG}.py`. Describes prespecified case categories and eligibility only. "
           "It contains no model results, and cases are never added or dropped based on model behaviour.", "",
           "**Pre-declared batch rule.** With 12 independent cases (6 base + 6 extension) the case-clustered intervals "
           "are wide, so the PI approved expanding the development set to 36 cases as a separately declared batch run "
           "(three batches of 8: `ba`, `bb`, `bc`). This batch is run separately with the same frozen model configuration "
           "(`configs/p2_dev_eval_v1.json`), renderer, system prompt, task text and condition matrix as the base run "
           "(`stimuli_dev.jsonl`, sha256 `368e1d0e…8e67`) and the extension run (`stimuli_ext.jsonl`, sha256 `c9d92a01…63d0`). "
           "The batch was authored after the 12-case run; its cases were not selected or edited based on any model output, "
           "and base and extension artifacts are unchanged. Batch results are reported as a separately declared batch, "
           "never merged silently into the 12-case results.", "",
           f"- Independent cases in this batch: **{len(CASES_BA)}** (all synthetic, builder-written development cases; "
           "pending welfare-expert review)",
           f"- Combined with base + extension: **{len(allc)}** cases, {len(fam(allc))} distinct species × practice × "
           f"indicator families (batch families new to the set: {len(fam(CASES_BA) - fam(prior))} of {len(CASES_BA)})",
           f"- Cells per case: {n_cells} (10 conditions; E and E_scope crossed with 3 outcome directions)",
           f"- Contexts per cell: {len(r.CONTEXTS)} ({', '.join(r.CONTEXTS)})",
           f"- Eligibility: every case is eligible for every cell by construction "
           f"({len(CASES_BA)} × {n_cells} = {len(CASES_BA) * n_cells} cells, all filled)", ""]
    for dim in ("species", "practice_type", "indicator_type", "issuer"):
        cnt = collections.Counter(k[dim] for k in CASES_BA)
        out += [f"## By {dim}", "", "| value | cases |", "|---|---|"]
        out += [f"| {v} | {n} |" for v, n in sorted(cnt.items())] + [""]
    out += ["## Outcome audit method per case", "", "| case | outcome item | outcome method |", "|---|---|---|"]
    out += [f"| {k['id']} | {k['outcome_item']} | {k['outcome_method']} |" for k in CASES_BA] + [""]
    out += ["## Section 2 length per cell (characters)", "",
            "Lengths are not padded. Every cell ends with the same fixed filing notes, so differences equal "
            "the audit content that defines the condition (ledger P1, P3, P4).", "",
            "| case | " + " | ".join(f"{c}/{d[:3]}" if d != "none" else c for c, d in r.cells()) + " |",
            "|---|" + "---|" * len(r.cells())]
    out += [f"| {k['id']} | " + " | ".join(str(len(r.audit_section(k, c, d))) for c, d in r.cells()) + " |"
            for k in CASES_BA] + [""]
    out += ["## What this batch adds", "",
            "- **Species:** breeding ewes, dairy goats, feedlot beef cattle, farmed red deer, alpacas, livery horses, "
            "farrowing sows and litters, dairy water buffalo (prior 12: broilers, laying hens, pigs, dairy cows, salmon, turkeys, "
            "ducks, rabbits, dairy calves).",
            "- **Practice types:** treatment protocol, milking hygiene, shade provision, transport duration, grazing stocking "
            "rate, forage ration, farrowing pen design, bedding depth.",
            "- **Outcome evidence sources and windows:** contracted scorer (4 visits a year), medicine book and vet notes "
            "reconciled with prescriptions (per year), camera-based sensor logs (15:00 daily, June to September), abattoir "
            "dressing reports (per consignment), veterinary laboratory reports (4 sampling rounds a year), vet call-out log "
            "reconciled with practice visit records (per resident horse), herd software reconciled with fallen-stock tickets "
            "(per litter), milk-recording technician scoring (4 quarterly visits).",
            "- **Issuers:** eight new fictional issuers (none shared with the base or extension sets).", "",
            "## Not covered (known gaps, unchanged by this batch)", "",
            "- **Template diversity: one family.** Batch cases use the same audit-record layout (`kv-record-v1`) and dossier "
            "layout as the base cases, by design (same renderer). Format-specific behaviour still cannot be separated from the effect.",
            "- **Period and population scope.** No condition varies the audited period or audits a subset of the population.",
            "- **Independence.** All cases come from builder sessions working to one convention set. Analysis must cluster on case.",
            "- **Realism.** Thresholds, indicators and methods are unreviewed placeholders (spec §8.6). "
            "`EXPERT_VERDICTS.csv` has no rows for this batch yet (human-owned; not written by any generator).", ""]
    with open(os.path.join(HERE, f"COVERAGE_{TAG}.md"), "w") as f:
        f.write("\n".join(out))


def write_rubric():
    out = [f"# Claim-evidence rubric for expert review (expansion batch {TAG})", "",
           f"Generated by `generate_{TAG}.py`. Same structure as `CLAIM_EVIDENCE_RUBRIC.md`. **Builder rationale is not "
           "validation.** Expert verdicts go in `EXPERT_VERDICTS.csv`, keyed by row id; that file is human-owned and never "
           "written by a generator.", ""]
    for k in CASES_BA:
        out += [f"## {k['id']} ({k['species']}; issuer {k['issuer']})", "",
                "| Row id | Claim (cells where gold = T/F) | Claim text | Record: item / method / finding | Builder: scope and residual risk |",
                "|---|---|---|---|---|"]
        out += ["| " + " | ".join(row) + " |" for row in g.rubric_rows(k)] + [""]
    with open(os.path.join(HERE, f"CLAIM_EVIDENCE_RUBRIC_{TAG}.md"), "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    rows = write_rendered()
    write_matrix(rows)
    write_coverage()
    write_rubric()
    print(f"{len(rows)} stimuli, {len(CASES_BA)} batch-{TAG} cases, {len(r.cells())} cells")
